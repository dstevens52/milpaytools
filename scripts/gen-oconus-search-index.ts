// Generates src/data/oconus/searchIndex.generated.ts — the slim overseas search
// index the calculators' station input ships to the browser. Importing the full
// v2 registry client-side added ~6.5 KB gzipped per calculator page; this file
// carries only name, shortName, slug and searchAliases for published stations.
//
// Runs in `prebuild` (so a deploy always regenerates it) and via
// `npm run gen:oconus-index`. The output is committed so `next dev`, tsc and the
// tests work without a build; tests/e2e/oconus-station-search.spec.ts fails if
// the committed file drifts from the registry.
//
//   npx tsx scripts/gen-oconus-search-index.ts

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildOconusSearchIndex } from '../src/data/oconus/buildSearchIndex';

const OUT = join(__dirname, '..', 'src', 'data', 'oconus', 'searchIndex.generated.ts');

const index = buildOconusSearchIndex();
// An empty index proves nothing — refuse to write one.
if (index.length === 0) {
  console.error('gen-oconus-search-index: no published v2 stations — refusing to write an empty index');
  process.exit(1);
}

const body = `// GENERATED by scripts/gen-oconus-search-index.ts from the v2 OCONUS registry
// (src/data/oconus/index.ts). Do not edit by hand — edit the station files and run
// \`npm run gen:oconus-index\` (also runs in prebuild).

import type { OconusSearchEntry } from './buildSearchIndex';

export const OCONUS_SEARCH_INDEX: OconusSearchEntry[] = ${JSON.stringify(index, null, 2)};
`;

writeFileSync(OUT, body, 'utf8');
console.log(`gen-oconus-search-index: ${index.length} published station(s) → ${OUT}`);
