// Generates src/data/duty-stations/searchIndex.generated.ts — the slim station index the
// calculators' station input (and the PCS calculator) ship to the browser instead of the full
// DUTY_STATIONS records (P1 #2, docs/perf/p1-step1-report.md).
//
// Runs in `prebuild` (so a deploy always regenerates it) and via `npm run gen:station-index`.
// The output is committed so `next dev`, tsc and the tests work without a build;
// tests/e2e/station-search-index.spec.ts fails if the committed file drifts from stations.ts.
//
//   npx tsx scripts/gen-station-search-index.ts

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildStationSearchIndex } from '../src/data/duty-stations/buildSearchIndex';

const OUT = join(__dirname, '..', 'src', 'data', 'duty-stations', 'searchIndex.generated.ts');

const index = buildStationSearchIndex();
// An empty index proves nothing — refuse to write one.
if (index.length === 0) {
  console.error('gen-station-search-index: DUTY_STATIONS is empty — refusing to write an empty index');
  process.exit(1);
}

const body = `// GENERATED by scripts/gen-station-search-index.ts from src/data/duty-stations/stations.ts.
// Do not edit by hand — edit stations.ts and run \`npm run gen:station-index\` (also runs in prebuild).

import type { StationSearchEntry } from './buildSearchIndex';

export const STATION_SEARCH_INDEX: StationSearchEntry[] = ${JSON.stringify(index, null, 2)};
`;

writeFileSync(OUT, body, 'utf8');
console.log(`gen-station-search-index: ${index.length} station(s) → ${OUT}`);
