const VA_SUBSEQUENT_LT5 = VA_PURCHASE_FUNDING_FEE.subsequent.lt5;

// VA entitlement calculator (build V2). Unit tests: no page is opened.
// Rules: docs/sources/va-entitlement-loan-limits-2027.md. Run: npm run test:va-entitlement

const ROOT = process.cwd();

test.describe('entitlement math (VA examples)', () => {
  test("VA.gov's worked example: $900,000 limit, $50,000 used", () => {
    const r = remainingEntitlement(900_000, 50_000);
    expect(r).toBe(175_000);
    expect(maxZeroDownLoan(r)).toBe(700_000);
  });

  test("VA's archived guaranty example: $480,000 loan, $104,250 remaining → $15,750 down", () => {
    expect(typicalDownPayment(480_000, 104_250)).toBe(15_750);
  });

  test('2027 baseline: $855,400 limit, $50,000 used → $163,850 remaining, $655,400 max', () => {
    const r = remainingEntitlement(855_400, 50_000);
    expect(r).toBe(163_850);
    expect(maxZeroDownLoan(r)).toBe(655_400);
  });

  test('2026 baseline keeps its cents: $158,187.50 remaining, $632,750 max', () => {
    const r = remainingEntitlement(832_750, 50_000);
    expect(r).toBe(158_187.5);
    expect(usdExact(r)).toBe('$158,187.50');
    expect(usdExact(maxZeroDownLoan(r))).toBe('$632,750');
  });

  test('remaining floors at 0; down payment floors at 0', () => {
    expect(remainingEntitlement(855_400, 300_000)).toBe(0);
    expect(maxZeroDownLoan(0)).toBe(0);
    expect(typicalDownPayment(400_000, 163_850)).toBe(0);
  });

  test('prior-loan estimate: $300,000 → $75,000; $120,000 and $144,000 → null', () => {
    expect(estimatedUsedFromPriorLoan(300_000)).toBe(75_000);
    expect(estimatedUsedFromPriorLoan(120_000)).toBeNull();
    expect(estimatedUsedFromPriorLoan(144_000)).toBeNull();
    expect(estimatedUsedFromPriorLoan(144_001)).toBe(36_000.25);
  });

  test('calcEntitlement: above the max → typical down; subsequent-use fee; exempt → $0', () => {
    const r = calcEntitlement({ countyLimit: 855_400, used: 50_000, price: 700_000, down: 0, feeStatus: 'none' });
    expect(r.maxZeroDown).toBe(655_400);
    expect(r.aboveMax).toBe(true);
    expect(r.typicalDown).toBe(0.25 * 700_000 - 163_850); // 11,150
    expect(r.feeRate).toBe(VA_SUBSEQUENT_LT5);
    expect(r.feeAmount).toBe(Math.round(700_000 * VA_SUBSEQUENT_LT5));
    const ex = calcEntitlement({ countyLimit: 855_400, used: 50_000, price: 700_000, down: 0, feeStatus: 'comp' });
    expect(ex.exempt).toBe(true);
    expect(ex.feeAmount).toBe(0);
    // No price: the fee is on the $0-down maximum, and there is no down payment line.
    const np = calcEntitlement({ countyLimit: 855_400, used: 50_000, price: 0, down: 0, feeStatus: 'none' });
    expect(np.loan).toBe(655_400);
    expect(np.aboveMax).toBe(false);
  });

  test('county names: title case, Mc and O’ names, small words', () => {
    expect(countyDisplayName("PRINCE GEORGE'S COUNTY")).toBe("Prince George's County");
    expect(countyDisplayName('MCLEAN COUNTY')).toBe('McLean County');
    expect(countyDisplayName("O'BRIEN COUNTY")).toBe("O'Brien County");
    expect(countyDisplayName('MIAMI-DADE COUNTY')).toBe('Miami-Dade County');
    expect(countyDisplayName('LEWIS AND CLARK COUNTY')).toBe('Lewis and Clark County');
  });
});

/** Read a source CSV and the header line of the generated TS. */
function sha256(file: string): string {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

const DATA: [number, readonly CountyLoanLimitRow[]][] = [
  [2026, LOAN_LIMITS_2026],
  [2027, LOAN_LIMITS_2027],
];

test.describe('FHFA county data (generated by scripts/build-loan-limits.py)', () => {
  for (const [year, rows] of DATA) {
    test(`${year}: SHA-256, row count and checks match the source file`, () => {
      const s = LOAN_LIMIT_SUMMARIES[year];
      const csv = path.join(ROOT, 'data', 'sources', 'fhfa', s.file);
      expect(fs.existsSync(csv), csv).toBe(true);
      expect(sha256(csv)).toBe(s.sha256);
      const ts = fs.readFileSync(path.join(ROOT, 'src', 'data', 'va-loan', `loanLimits${year}.ts`), 'utf-8');
      expect(ts).toContain(`SHA-256 of the raw CSV: ${s.sha256}`);

      expect(rows.length).toBe(s.counties);
      expect(rows.length).toBeGreaterThanOrEqual(3200);
      expect(rows.length).toBeLessThan(3300);
      expect(new Set(rows.map((r) => r[0])).size).toBe(rows.length);
      for (const r of rows) {
        expect(r[0]).toMatch(/^\d{5}$/);
        expect(LOAN_LIMIT_STATE_NAMES[r[1]], r[1]).toBeTruthy();
        expect(Number.isInteger(r[3]) && r[3] > 0).toBe(true);
      }

      // Most common value = baseline; max outside AK/HI/GU/VI = ceiling (source file).
      const counts = new Map<number, number>();
      for (const r of rows) counts.set(r[3], (counts.get(r[3]) ?? 0) + 1);
      const mode = [...counts.entries()].sort((a, b) => b[1] - a[1])[0][0];
      expect(mode).toBe(s.baseline);
      const special = new Set(['AK', 'HI', 'GU', 'VI']);
      expect(Math.max(...rows.filter((r) => !special.has(r[1])).map((r) => r[3]))).toBe(s.ceiling);
      expect(Math.min(...rows.map((r) => r[3]))).toBe(s.baseline);
    });
  }

  test('the source file figures: 2026 $832,750 / $1,249,125; 2027 $855,400 / $1,283,100, AK/HI/GU/VI $1,283,100–$1,924,650', () => {
    expect(LOAN_LIMIT_SUMMARIES[2026].baseline).toBe(832_750);
    expect(LOAN_LIMIT_SUMMARIES[2026].ceiling).toBe(1_249_125);
    expect(LOAN_LIMIT_SUMMARIES[2027].baseline).toBe(855_400);
    expect(LOAN_LIMIT_SUMMARIES[2027].ceiling).toBe(1_283_100);
    expect(LOAN_LIMIT_SUMMARIES[2027].specialMin).toBeGreaterThanOrEqual(1_283_100);
    expect(LOAN_LIMIT_SUMMARIES[2027].specialMax).toBeLessThanOrEqual(1_924_650);
    // "an increase of $22,650 from 2026"
    expect(LOAN_LIMIT_SUMMARIES[2027].baseline - LOAN_LIMIT_SUMMARIES[2026].baseline).toBe(22_650);
  });

  test('both years list the same counties (the picker uses one list)', () => {
    expect(LOAN_LIMITS_2027.map((r) => r[0])).toEqual(LOAN_LIMITS_2026.map((r) => r[0]));
    expect(LOAN_LIMITS_2027.map((r) => r[2])).toEqual(LOAN_LIMITS_2026.map((r) => r[2]));
  });
});

test.describe('loan limit year', () => {
  test('before the Jan. 1 flip: 2026 and 2027, labeled by closing year', () => {
    expect(LOAN_LIMIT_YEAR).toBe(2026);
    expect(loanLimitYearsShown()).toEqual([2026, 2027]);
    expect(loanLimitYearLabel(2026)).toBe('Closing in 2026');
    expect(loanLimitYearLabel(2027)).toBe('Closing in 2027 (from Jan. 1)');
  });

  test('after the flip: 2027 only', () => {
    expect(loanLimitYearsShown(2027)).toEqual([2027]);
    expect(loanLimitYearLabel(2027, 2027)).toBe('Closing in 2027');
  });

  test('a year with no file is an error, never a silent fallback', () => {
    expect(() => loanLimitYearsShown(2025)).toThrow();
  });
});

test.describe('<VaEntitlementFigure> (blog posts)', () => {
  const cur = LOAN_LIMIT_SUMMARIES[LOAN_LIMIT_YEAR];

  test('figures come from the lib and the current year', () => {
    expect(vaEntitlementFigure({ show: 'year' })).toBe(String(LOAN_LIMIT_YEAR));
    expect(vaEntitlementFigure({ show: 'limit' })).toBe(usdExact(cur.baseline));
    expect(vaEntitlementFigure({ prior: '280000', show: 'used' })).toBe('$70,000');
    const remaining = 0.25 * cur.baseline - 70_000;
    expect(vaEntitlementFigure({ prior: '280000', show: 'remaining' })).toBe(usdExact(remaining));
    expect(vaEntitlementFigure({ prior: '280000', show: 'max' })).toBe(usdExact(4 * remaining));
    expect(vaEntitlementFigure({ prior: '280000', price: '650000', show: 'required' })).toBe('$162,500');
    expect(vaEntitlementFigure({ prior: '280000', price: '650000', show: 'down' })).toBe(usdExact(162_500 - remaining));
    expect(vaEntitlementFigure({ show: 'basicMax' })).toBe('$144,000');
    expect(vaEntitlementFigure({ year: 'next', show: 'limit' })).toBe(usdExact(LOAN_LIMIT_SUMMARIES[LOAN_LIMIT_YEAR + 1].baseline));
  });

  test('bad inputs throw at build time', () => {
    expect(() => vaEntitlementFigure({ prior: '120000', show: 'used' })).toThrow(/144,000/);
    expect(() => vaEntitlementFigure({ prior: '280000', price: '350000', show: 'down' })).toThrow(/maximum/);
    expect(() => vaEntitlementFigure({ used: 'abc' })).toThrow();
    expect(() => vaEntitlementFigure({ year: '2025', show: 'limit' })).toThrow();
  });
});
